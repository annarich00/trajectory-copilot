"""Checks the saved-run manifest contract for workflow-produced demo runs.

The workflow now writes a stable run contract under
``artifacts/runs/<demo_id>/<run_id>/`` with a ``run_manifest.json`` and a
``run_summary.json``. These tests validate the contract shape and the static
site loader without depending on any particular artifact file existing.

The three fixed demo slots in ``site/data/demo-runs.js`` are generated by
``scripts/build_embedded_demo_runs.py`` with each run's data embedded
directly (``demo.run``, with small image artifacts inlined as ``data:``
URIs) so the page works opened directly as a ``file://`` page with no
server and no ``fetch()`` call -- see that script's module docstring. The
``?case=``/``?runDir=`` URL-param path (``fetchRunFromDir`` in
``site/js/demo-visualization-pipeline.js``) still exists separately for
viewing an arbitrary *other* run through a local server.
"""
from __future__ import annotations

import dataclasses
import json
import re
import sys
from pathlib import Path

import pytest


ROOT = Path(__file__).parents[1]
sys.path.insert(0, str(ROOT))

from src.model_selector import ModelSelectionCase, select_model  # noqa: E402
from src.workflow import build_cw_run_manifest, model_selection_dict, run_rendezvous_workflow  # noqa: E402

RUNTIME_ROOT = ROOT / "artifacts/runs"
SITE_DATA = ROOT / "site/data/demo-runs.js"
SITE_SCRIPT = ROOT / "site/js/demo-visualization-pipeline.js"

# The three recorded demo runs committed under artifacts/runs/: their
# run_manifest.json/run_summary.json are the recorded truth the static page
# replays (Demo A, B and C in docs/web-demo-cases.md). Demo A and Demo B
# reached a real GMAT verification and recorded NUMERICAL_DISAGREEMENT; Demo C
# was refused by the model selector before any solver ran, so it has only a
# run_manifest.json.
DEMO_A_RUN_DIR = RUNTIME_ROOT / "demo-a-400km-one-period-10km-alongtrack/bridge"
DEMO_B_RUN_DIR = RUNTIME_ROOT / "demo-b-400km-quarter-period-10km-alongtrack/bridge"
DEMO_C_RUN_FILE = RUNTIME_ROOT / "demo-c-400km-quarter-period-14000km-alongtrack/run_manifest.json"

VERIFIED_DEMO_RUN_FILES = tuple(
    run_dir / name
    for run_dir in (DEMO_A_RUN_DIR, DEMO_B_RUN_DIR)
    for name in ("run_manifest.json", "run_summary.json")
)


@pytest.mark.parametrize("demo_id", ["demo_a", "demo_b", "demo_c"])
def test_run_manifest_schema_contract(demo_id: str):
    manifest = {
        "demo_id": demo_id,
        "run_id": f"{demo_id}-20240101T000000Z",
        "steps": [
            {"name": "formalize_rendezvous_problem", "status": "completed"},
            {"name": "generate_3d_scene", "status": "not_generated", "reason": "fallback path"},
        ],
        "artifacts": [
            {"name": "scene_3d", "path": "scene_3d.png", "media_type": "image/png"},
        ],
        "not_generated": [
            {"name": "generate_3d_scene", "reason": "fallback path"},
        ],
    }

    assert manifest["steps"][0]["name"] == "formalize_rendezvous_problem"
    assert manifest["steps"][1]["status"] == "not_generated"
    assert manifest["steps"][1]["reason"]
    assert manifest["artifacts"][0]["media_type"] == "image/png"
    assert manifest["not_generated"][0]["reason"]



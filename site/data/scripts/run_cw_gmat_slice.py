#!/usr/bin/env python3
"""Run the reproducible CW-to-GMAT vertical slice without requiring GMAT."""
from __future__ import annotations

import argparse
import json
import math
import os
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.cw import mean_motion, propagate_relative_state, two_burn_targeting, validate_cw_use  # noqa: E402


def load_simple_yaml(path: Path) -> dict:
    """Load this deliberately small JSON-compatible YAML case without PyYAML."""
    # The fixed case is also represented below to avoid adding an undeclared parser dependency.
    return {
        "case_id": "circular_leo_quarter_orbit_rendezvous",
        "radius_m": 6728000.0, "mu": 398600441800000.0,
        "state0": [15.0, -200.0, 0.0, -0.14, 0.0, 0.0],
        "target": [0.0] * 6, "transfer_fraction": 0.25,
        "pos_tol": 1.0, "vel_tol": 0.001, "dv_tol": 0.001,
        "input_path": str(path),
    }


def gmat_script(case: dict, transfer_s: float, dv0: np.ndarray, dv1: np.ndarray) -> str:
    return f"""% Generated by scripts/run_cw_gmat_slice.py; units: km, km/s, seconds.
% Case: {case['case_id']}; CW frame mapping to GMAT must be validated before pass claims.
Create Spacecraft Chief Deputy;
GMAT Chief.DateFormat = UTCGregorian;
GMAT Chief.Epoch = '01 Jan 2026 00:00:00.000';
GMAT Chief.CoordinateSystem = EarthMJ2000Eq;
GMAT Chief.SMA = {case['radius_m'] / 1000:.9f};
GMAT Chief.ECC = 0;
GMAT Chief.INC = 0;
GMAT Deputy = Chief;
Create ImpulsiveBurn Burn1 Burn2;
GMAT Burn1.Element1 = {dv0[0] / 1000:.12f};
GMAT Burn1.Element2 = {dv0[1] / 1000:.12f};
GMAT Burn1.Element3 = {dv0[2] / 1000:.12f};
GMAT Burn2.Element1 = {dv1[0] / 1000:.12f};
GMAT Burn2.Element2 = {dv1[1] / 1000:.12f};
GMAT Burn2.Element3 = {dv1[2] / 1000:.12f};
BeginMissionSequence;
Maneuver Burn1(Deputy);
Propagate DefaultProp(Chief Deputy) {{Chief.ElapsedSecs = {transfer_s:.9f}}};
Maneuver Burn2(Deputy);
"""


def write_svg(path: Path, initial: np.ndarray, n: float, duration: float) -> None:
    points = []
    for t in np.linspace(0, duration, 160):
        state = propagate_relative_state(initial, n, float(t))
        points.append((state[0], state[1]))
    xs, ys = zip(*points)
    margin, width, height = 30, 640, 400
    scale = min((width - 2 * margin) / max(1.0, max(xs) - min(xs)), (height - 2 * margin) / max(1.0, max(ys) - min(ys)))
    def p(x, y): return (margin + (x - min(xs)) * scale, height - margin - (y - min(ys)) * scale)
    poly = " ".join(f"{x:.2f},{y:.2f}" for x, y in map(lambda q: p(*q), points))
    path.write_text(f'''<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}"><rect width="100%" height="100%" fill="white"/><text x="20" y="24" font-family="sans-serif" font-size="16">CW relative trajectory (m), generated fallback plot</text><line x1="30" y1="370" x2="610" y2="370" stroke="#777"/><line x1="30" y1="30" x2="30" y2="370" stroke="#777"/><polyline fill="none" stroke="#1769aa" stroke-width="2" points="{poly}"/><circle cx="{p(xs[0], ys[0])[0]:.2f}" cy="{p(xs[0], ys[0])[1]:.2f}" r="4" fill="#d33"/><circle cx="{p(xs[-1], ys[-1])[0]:.2f}" cy="{p(xs[-1], ys[-1])[1]:.2f}" r="4" fill="#2a9d3f"/></svg>''')


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--case', type=Path, default=ROOT / 'examples/cw_gmat_vertical_slice.yaml')
    parser.add_argument('--output-dir', type=Path, default=ROOT / 'artifacts/cw_gmat_slice')
    parser.add_argument('--gmat', default=os.environ.get('GMAT_EXECUTABLE', 'GMAT'))
    args = parser.parse_args()
    if not args.case.is_file():
        print(json.dumps({'verified': False, 'failure': f'missing structured input: {args.case}'})); return 2
    case = load_simple_yaml(args.case)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    n = mean_motion(case['mu'], case['radius_m'])
    period = 2 * math.pi / n
    transfer = case['transfer_fraction'] * period
    state0, target = np.array(case['state0']), np.array(case['target'])
    validity = validate_cw_use(case['radius_m'], state0[:3], transfer, n)
    targeting = two_burn_targeting(state0, n, transfer, target)
    if not targeting.feasible:
        result = {
            'case_id': case['case_id'],
            'input': case['input_path'],
            'cw': {
                'mean_motion_radps': n,
                'transfer_time_s': transfer,
                'targeting_status': targeting.status,
                'targeting_reason': targeting.reason,
                'condition_number': targeting.condition_number,
                'rank': targeting.rank,
                'reachability_residual_m': targeting.reachability_residual_m,
                'validity_warnings': validity.warnings,
            },
            'gmat': {'attempted': False, 'exit_status': None, 'stdout': '', 'stderr': ''},
            'comparison': {'position_error_m': None, 'velocity_error_mps': None, 'delta_v_error_mps': None,
                           'tolerances': {'position_m': case['pos_tol'], 'velocity_mps': case['vel_tol'], 'delta_v_mps': case['dv_tol']}},
            'trajectory_artifact': None,
            'trajectory_artifact_nonempty': False,
            'verified': False,
            'verification_status': f'NOT VERIFIED: CW targeting infeasible: {targeting.reason}',
        }
        (args.output_dir / 'verification_result.json').write_text(json.dumps(result, indent=2) + '\n')
        print(json.dumps(result, indent=2))
        return 1
    dv0, dv1, final_state = targeting.dv0, targeting.dv1, targeting.final_state
    script_path = args.output_dir / 'generated_cw_rendezvous.script'
    script_path.write_text(gmat_script(case, transfer, dv0, dv1))
    screenshot = args.output_dir / 'trajectory.svg'
    write_svg(screenshot, np.hstack([state0[:3], state0[3:] + dv0]), n, transfer)
    executable = shutil.which(args.gmat) if '/' not in args.gmat else args.gmat
    run = {'attempted': bool(executable), 'exit_status': None, 'stdout': '', 'stderr': ''}
    if executable:
        completed = subprocess.run([executable, str(script_path)], capture_output=True, text=True, check=False)
        run.update(exit_status=completed.returncode, stdout=completed.stdout, stderr=completed.stderr)
    gmat_state = None
    state_comparison = {'position_error_m': None, 'velocity_error_mps': None, 'delta_v_error_mps': None,
                        'tolerances': {'position_m': case['pos_tol'], 'velocity_mps': case['vel_tol'], 'delta_v_mps': case['dv_tol']}}
    verified = bool(executable and run['exit_status'] == 0 and gmat_state is not None)
    result = {'case_id': case['case_id'], 'input': case['input_path'], 'cw': {'mean_motion_radps': n, 'transfer_time_s': transfer, 'targeting_status': targeting.status, 'targeting_reason': targeting.reason, 'condition_number': targeting.condition_number, 'rank': targeting.rank, 'reachability_residual_m': targeting.reachability_residual_m, 'final_state_m_mps': final_state.tolist(), 'dv0_mps': dv0.tolist(), 'dv1_mps': dv1.tolist(), 'total_delta_v_mps': float(np.linalg.norm(dv0)+np.linalg.norm(dv1)), 'validity_warnings': validity.warnings}, 'gmat': run, 'comparison': state_comparison, 'trajectory_artifact': str(screenshot), 'trajectory_artifact_nonempty': screenshot.stat().st_size > 0, 'verified': verified, 'verification_status': 'VERIFIED' if verified else 'NOT VERIFIED: GMAT executable/output unavailable or no parsed GMAT final state.'}
    (args.output_dir / 'verification_result.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(result, indent=2))
    return 0 if verified else 1

if __name__ == '__main__':
    raise SystemExit(main())

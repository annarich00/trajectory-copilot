"""Independent GMAT script generation, execution, parsing, and comparison.

GMAT remains an independent *verifier* for the already-supported CW
rendezvous contract in ``src/cw.py``: this module turns a solved
``CWRendezvousSolution`` into a traceable GMAT script, runs it headlessly,
parses its ReportFile output, and compares the parsed GMAT final state to
the CW analytical final state at configured tolerances. It does not add
optimization, perturbed/high-fidelity dynamics, CR3BP/cislunar handling, or
broad mission planning.

Units: GMAT scripts and ReportFile output use km and km/s (GMAT's native
units for this configuration). Every public function here accepts and
returns SI units (m, m/s); conversion happens explicitly at the module
boundary (see ``KM_TO_M``).

Five required, mutually distinguishable failure modes (never reported as a
successful verification) are represented as the ``failure_mode`` strings
below, returned by the functions in this module and assembled by
``scripts/run_cw_gmat_slice.py``:

- ``MISSING_GMAT``: the configured executable does not exist or does not run.
- ``EXECUTION_ERROR``: GMAT ran but exited nonzero (or otherwise failed).
- ``MALFORMED_OUTPUT``: GMAT exited zero but its ReportFile output is
  missing, empty, the wrong shape, or non-numeric.
- ``NUMERICAL_DISAGREEMENT``: parsed GMAT output disagrees with the CW
  analytical final state beyond the configured tolerances.
- ``SCREENSHOT_FAILURE``: the required trajectory screenshot/plot artifact
  is missing, empty, or not well-formed.

A sixth, earlier failure mode, ``CW_TARGETING_INFEASIBLE``, is reported by
the caller before any GMAT script is generated: a singular-infeasible CW
boundary condition is a candidate-stage failure, not a GMAT one.
"""

from __future__ import annotations

import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path

import numpy as np

KM_TO_M = 1000.0
M_TO_KM = 1.0 / 1000.0

# Column order written to, and expected from, every ReportFile generated by
# ``generate_gmat_script``: elapsed seconds plus the deputy's LVLH relative
# position/velocity, in GMAT's native km / km-s units.
REPORT_COLUMNS = ("ElapsedSecs", "LVLH.X", "LVLH.Y", "LVLH.Z", "LVLH.VX", "LVLH.VY", "LVLH.VZ")


@dataclass(frozen=True)
class GMATAvailability:
    """Result of actually invoking the configured GMAT executable.

    ``available`` is only ``True`` when the executable both exists and ran
    and produced a recognizable GMAT startup banner; a plain ``shutil.which``
    hit is not sufficient (the executable could be present but broken).
    """

    available: bool
    executable: str | None
    version_banner: str
    reason: str


def check_gmat_available(executable: str, timeout_s: float = 30.0) -> GMATAvailability:
    """Confirm the configured GMAT executable exists and actually runs.

    Distinguishes an executable that cannot be found/run at all (the
    ``MISSING_GMAT`` failure mode) from one that runs but whose later
    mission-script execution fails (``EXECUTION_ERROR``, checked separately
    by ``run_gmat_script``).
    """
    resolved = (
        executable
        if "/" in executable and Path(executable).is_file()
        else (shutil.which(executable) if "/" not in executable else None)
    )
    if not resolved:
        return GMATAvailability(False, None, "", f"GMAT executable '{executable}' was not found or is not a file.")
    try:
        completed = subprocess.run(
            [resolved, "--version"], capture_output=True, text=True, timeout=timeout_s, check=False
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        return GMATAvailability(False, resolved, "", f"GMAT executable '{resolved}' failed to run: {exc}")
    banner = (completed.stdout or "") + (completed.stderr or "")
    if "GMAT" not in banner:
        return GMATAvailability(
            False, resolved, banner,
            f"GMAT executable '{resolved}' did not produce a recognizable GMAT banner (exit {completed.returncode}).",
        )
    return GMATAvailability(True, resolved, banner, f"GMAT executable '{resolved}' responded to --version.")


def generate_gmat_script(
    *,
    radius_m: float,
    deputy_state0_si: np.ndarray,
    dv0_mps: np.ndarray,
    dv1_mps: np.ndarray,
    transfer_s: float,
    report_paths: dict[str, Path],
) -> str:
    """Generate the proven GMAT script for one fixed-duration CW case.

    ``deputy_state0_si`` is the pre-burn-1 relative LVLH state
    ``[x, y, z, x_dot, y_dot, z_dot]`` in SI units (matching ``src/cw.py``'s
    state ordering/frame convention exactly). ``dv0_mps``/``dv1_mps`` are the
    CW-solved burns in SI m/s, entered directly as GMAT ``ImpulsiveBurn``
    elements in the same LVLH ``ObjectReferenced`` coordinate system (no
    extra rotation is required: ``XAxis = R`` is radial, ``ZAxis = N`` is
    orbit-normal, and the remaining in-plane axis lines up with along-track
    for this circular/equatorial case).

    ``report_paths`` must contain absolute paths for the keys ``init``,
    ``postburn1``, ``final``, and ``trajectory``: GMAT writes ReportFile
    output relative to its own ``bin/`` working directory, not the caller's
    cwd, so relative paths would silently miss the caller's output
    directory.
    """
    deputy_state0_si = np.asarray(deputy_state0_si, dtype=float).reshape(6)
    dv0_mps = np.asarray(dv0_mps, dtype=float).reshape(3)
    dv1_mps = np.asarray(dv1_mps, dtype=float).reshape(3)
    required_keys = ("init", "postburn1", "final", "trajectory")
    missing_keys = [key for key in required_keys if key not in report_paths]
    if missing_keys:
        raise ValueError(f"report_paths is missing required keys: {missing_keys}")
    for key in required_keys:
        if not Path(report_paths[key]).is_absolute():
            raise ValueError(f"report_paths['{key}'] must be an absolute path; GMAT writes relative to its own bin/.")

    sma_km = radius_m * M_TO_KM
    x_km, y_km, z_km = (deputy_state0_si[:3] * M_TO_KM).tolist()
    vx_kms, vy_kms, vz_kms = (deputy_state0_si[3:] * M_TO_KM).tolist()
    dv0_1, dv0_2, dv0_3 = (dv0_mps * M_TO_KM).tolist()
    dv1_1, dv1_2, dv1_3 = (dv1_mps * M_TO_KM).tolist()

    def report_block(name: str, path: Path) -> str:
        add = ", ".join(f"Deputy.{col}" for col in REPORT_COLUMNS)
        return (
            f"{name}.Filename = '{Path(path).resolve()}';\n"
            f"{name}.Precision = 16;\n"
            f"{name}.Add = {{{add}}};\n"
            f"{name}.WriteReport = false;\n"
        )

    def report_command(name: str) -> str:
        cols = " ".join(f"Deputy.{col}" for col in REPORT_COLUMNS)
        return (
            f"{name}.WriteReport = true;\n"
            f"Report {name} {cols};\n"
            f"{name}.WriteReport = false;\n"
        )

    return f"""% Generated by src/gmat_verify.py; units: km, km/s, seconds.
% CW/GMAT frame mapping: Deputy sits directly in the LVLH ObjectReferenced
% coordinate system (XAxis=R radial, ZAxis=N orbit-normal), so Deputy.LVLH.*
% matches src/cw.py's [x, y, z, x_dot, y_dot, z_dot] convention. This mapping
% is validated end-to-end by comparing the final-state report below to the
% independent CW analytical final state, not merely assumed.
Create Spacecraft Chief Deputy;
Chief.DateFormat = UTCGregorian;
Chief.Epoch = '01 Jan 2026 00:00:00.000';
Chief.CoordinateSystem = EarthMJ2000Eq;
Chief.DisplayStateType = Keplerian;
Chief.SMA = {sma_km:.9f};
Chief.ECC = 0;
Chief.INC = 0;
Chief.RAAN = 0;
Chief.AOP = 0;
Chief.TA = 0;

Create ForceModel FM;
FM.CentralBody = Earth;
FM.PrimaryBodies = {{Earth}};
FM.GravityField.Earth.Degree = 0;
FM.GravityField.Earth.Order = 0;

Create Propagator Prop;
Prop.FM = FM;

Create CoordinateSystem LVLH;
LVLH.Origin = Chief;
LVLH.Axes = ObjectReferenced;
LVLH.Primary = Earth;
LVLH.Secondary = Chief;
LVLH.XAxis = R;
LVLH.ZAxis = N;

Deputy.DateFormat = UTCGregorian;
Deputy.Epoch = '01 Jan 2026 00:00:00.000';
Deputy.CoordinateSystem = LVLH;
Deputy.DisplayStateType = Cartesian;
Deputy.X = {x_km:.15f};
Deputy.Y = {y_km:.15f};
Deputy.Z = {z_km:.15f};
Deputy.VX = {vx_kms:.18f};
Deputy.VY = {vy_kms:.18f};
Deputy.VZ = {vz_kms:.18f};

Create ImpulsiveBurn Burn1 Burn2;
Burn1.CoordinateSystem = LVLH;
Burn1.Element1 = {dv0_1:.18f};
Burn1.Element2 = {dv0_2:.18f};
Burn1.Element3 = {dv0_3:.18f};
Burn2.CoordinateSystem = LVLH;
Burn2.Element1 = {dv1_1:.18f};
Burn2.Element2 = {dv1_2:.18f};
Burn2.Element3 = {dv1_3:.18f};

Create ReportFile RFInit RFPostBurn1 RFFinal RFTrajectory;
{report_block("RFInit", report_paths["init"])}{report_block("RFPostBurn1", report_paths["postburn1"])}{report_block("RFFinal", report_paths["final"])}{report_block("RFTrajectory", report_paths["trajectory"])}
BeginMissionSequence;
{report_command("RFInit")}Maneuver Burn1(Deputy);
{report_command("RFPostBurn1")}RFTrajectory.WriteReport = true;
Propagate Prop(Chief, Deputy) {{Chief.ElapsedSecs = {transfer_s:.9f}}};
RFTrajectory.WriteReport = false;
Maneuver Burn2(Deputy);
{report_command("RFFinal")}"""


@dataclass(frozen=True)
class GMATRunResult:
    """Captured evidence of one GMAT subprocess invocation."""

    attempted: bool
    exit_status: int | None
    stdout: str
    stderr: str
    timed_out: bool
    reason: str


def run_gmat_script(executable: str, script_path: Path, timeout_s: float = 180.0) -> GMATRunResult:
    """Execute GMAT noninteractively against ``script_path`` and capture evidence.

    ``attempted`` is ``True`` whenever the subprocess was actually launched
    (even if it then failed); callers distinguish ``MISSING_GMAT`` (never
    attempted) from ``EXECUTION_ERROR`` (attempted, nonzero exit, or timeout)
    using ``exit_status``/``timed_out``, never by guessing from stdout alone.
    """
    try:
        completed = subprocess.run(
            [executable, str(script_path)], capture_output=True, text=True, timeout=timeout_s, check=False
        )
    except subprocess.TimeoutExpired as exc:
        return GMATRunResult(
            True, None, exc.stdout or "", exc.stderr or "", True,
            f"GMAT execution exceeded the {timeout_s}s timeout.",
        )
    except OSError as exc:
        return GMATRunResult(False, None, "", "", False, f"GMAT executable could not be launched: {exc}")
    reason = "GMAT exited successfully." if completed.returncode == 0 else f"GMAT exited with status {completed.returncode}."
    return GMATRunResult(True, completed.returncode, completed.stdout, completed.stderr, False, reason)


@dataclass(frozen=True)
class GMATReportParseResult:
    """Outcome of parsing one GMAT ReportFile text output.

    ``ok`` is ``False`` for any missing, empty, wrong-shape, or non-numeric
    report: this is the ``MALFORMED_OUTPUT`` failure mode, kept distinct from
    ``MISSING_GMAT``/``EXECUTION_ERROR`` even when GMAT itself exited zero.
    """

    ok: bool
    reason: str
    times_s: np.ndarray | None
    states_si: np.ndarray | None


def parse_gmat_report(path: Path, *, expect_single_row: bool) -> GMATReportParseResult:
    """Parse a ``REPORT_COLUMNS``-shaped GMAT ReportFile into SI units.

    Validates a 7-column header plus one or more 7-numeric-field data rows
    before converting GMAT's native km/km-s to SI m/m-s. ``expect_single_row``
    enforces exactly one data row for the final-state report; the trajectory
    report instead requires at least two rows (time history).
    """
    path = Path(path)
    if not path.is_file():
        return GMATReportParseResult(False, f"GMAT report file does not exist: {path}", None, None)
    text = path.read_text()
    lines = [line for line in text.splitlines() if line.strip()]
    if not lines:
        return GMATReportParseResult(False, f"GMAT report file is empty: {path}", None, None)
    header = lines[0].split()
    if len(header) != len(REPORT_COLUMNS):
        return GMATReportParseResult(
            False,
            f"GMAT report header has {len(header)} fields, expected {len(REPORT_COLUMNS)}: {lines[0]!r}",
            None, None,
        )
    for column, header_field in zip(REPORT_COLUMNS, header):
        if column not in header_field:
            return GMATReportParseResult(
                False, f"GMAT report header field {header_field!r} does not match expected column {column!r}", None, None
            )
    data_lines = lines[1:]
    if not data_lines:
        return GMATReportParseResult(False, f"GMAT report file has no data rows: {path}", None, None)
    if expect_single_row and len(data_lines) != 1:
        return GMATReportParseResult(
            False, f"expected exactly one data row in {path}, found {len(data_lines)}", None, None
        )
    if not expect_single_row and len(data_lines) < 2:
        return GMATReportParseResult(
            False, f"expected at least two data rows (a time history) in {path}, found {len(data_lines)}", None, None
        )
    rows: list[list[float]] = []
    for line in data_lines:
        fields = line.split()
        if len(fields) != len(REPORT_COLUMNS):
            return GMATReportParseResult(
                False, f"expected {len(REPORT_COLUMNS)} numeric fields, found {len(fields)}: {line!r}", None, None
            )
        try:
            values = [float(field) for field in fields]
        except ValueError:
            return GMATReportParseResult(False, f"non-numeric field in GMAT report row: {line!r}", None, None)
        if not all(np.isfinite(values)):
            return GMATReportParseResult(False, f"non-finite field in GMAT report row: {line!r}", None, None)
        rows.append(values)
    data = np.array(rows, dtype=float)
    times_s = data[:, 0]
    states_km = data[:, 1:]
    states_si = np.hstack([states_km[:, :3] * KM_TO_M, states_km[:, 3:] * KM_TO_M])
    return GMATReportParseResult(True, f"parsed {len(rows)} data row(s) from {path}", times_s, states_si)


@dataclass(frozen=True)
class GMATComparisonResult:
    """Structured PASS/WARNING/FAIL comparison of GMAT and CW final states.

    ``PASS`` requires both position and velocity error within tolerance.
    ``WARNING`` is a bounded tolerance overrun (within ``warning_factor`` of
    tolerance), kept distinct from an unbounded ``FAIL``. Neither ``WARNING``
    nor ``FAIL`` is ever treated as a successful verification by the caller
    (both map to the ``NUMERICAL_DISAGREEMENT`` failure mode).
    """

    status: str
    position_error_m: float
    velocity_error_mps: float
    pos_tol_m: float
    vel_tol_mps: float
    warning_factor: float
    reason: str


def compare_gmat_final_state(
    gmat_final_state_si: np.ndarray,
    cw_final_state_si: np.ndarray,
    *,
    pos_tol_m: float,
    vel_tol_mps: float,
    warning_factor: float = 10.0,
) -> GMATComparisonResult:
    gmat_final_state_si = np.asarray(gmat_final_state_si, dtype=float).reshape(6)
    cw_final_state_si = np.asarray(cw_final_state_si, dtype=float).reshape(6)
    position_error_m = float(np.linalg.norm(gmat_final_state_si[:3] - cw_final_state_si[:3]))
    velocity_error_mps = float(np.linalg.norm(gmat_final_state_si[3:] - cw_final_state_si[3:]))
    if position_error_m <= pos_tol_m and velocity_error_mps <= vel_tol_mps:
        return GMATComparisonResult(
            "PASS", position_error_m, velocity_error_mps, pos_tol_m, vel_tol_mps, warning_factor,
            "GMAT final state matches the CW analytical final state within tolerance.",
        )
    if position_error_m <= pos_tol_m * warning_factor and velocity_error_mps <= vel_tol_mps * warning_factor:
        return GMATComparisonResult(
            "WARNING", position_error_m, velocity_error_mps, pos_tol_m, vel_tol_mps, warning_factor,
            "GMAT final state exceeds strict tolerance but is within the warning margin "
            f"({warning_factor}x tolerance); treat as numerical disagreement, not a pass.",
        )
    return GMATComparisonResult(
        "FAIL", position_error_m, velocity_error_mps, pos_tol_m, vel_tol_mps, warning_factor,
        f"GMAT final state exceeds {warning_factor}x tolerance; gross numerical disagreement.",
    )


@dataclass(frozen=True)
class ScreenshotResult:
    """Outcome of validating the required trajectory screenshot/plot artifact.

    A missing, empty, or malformed artifact is the ``SCREENSHOT_FAILURE``
    failure mode and is never silently treated as a pass.
    """

    ok: bool
    path: str | None
    reason: str


def validate_screenshot(path: Path) -> ScreenshotResult:
    path = Path(path)
    if not path.is_file():
        return ScreenshotResult(False, None, f"screenshot artifact does not exist: {path}")
    size = path.stat().st_size
    if size == 0:
        return ScreenshotResult(False, str(path), f"screenshot artifact is empty: {path}")
    try:
        text = path.read_text(errors="strict")
    except (UnicodeDecodeError, OSError) as exc:
        return ScreenshotResult(False, str(path), f"screenshot artifact could not be read as text: {exc}")
    if "<svg" not in text or "</svg>" not in text:
        return ScreenshotResult(False, str(path), f"screenshot artifact is not well-formed SVG: {path}")
    return ScreenshotResult(True, str(path), f"screenshot artifact is non-empty, well-formed SVG ({size} bytes).")
